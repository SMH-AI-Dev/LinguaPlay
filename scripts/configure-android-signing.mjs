import fs from "node:fs";

const gradleFile = "android/app/build.gradle";
if (!fs.existsSync(gradleFile)) {
  throw new Error("android/app/build.gradle was not generated by Capacitor.");
}

const required = [
  "LINGUAPLAY_ANDROID_KEYSTORE_FILE",
  "LINGUAPLAY_ANDROID_STORE_PASSWORD",
  "LINGUAPLAY_ANDROID_KEY_ALIAS",
  "LINGUAPLAY_ANDROID_KEY_PASSWORD",
];
for (const name of required) {
  if (!process.env[name]) throw new Error(`Missing required environment variable: ${name}`);
}

let gradle = fs.readFileSync(gradleFile, "utf8");
if (gradle.includes("signingConfigs.linguaplayRelease")) {
  console.log("Release signing is already configured.");
  process.exit(0);
}

const signingBlock = `
    signingConfigs {
        linguaplayRelease {
            storeFile file(System.getenv("LINGUAPLAY_ANDROID_KEYSTORE_FILE"))
            storePassword System.getenv("LINGUAPLAY_ANDROID_STORE_PASSWORD")
            keyAlias System.getenv("LINGUAPLAY_ANDROID_KEY_ALIAS")
            keyPassword System.getenv("LINGUAPLAY_ANDROID_KEY_PASSWORD")
        }
    }
`;

if (!/android\s*\{/.test(gradle)) throw new Error("Could not locate android { } block.");
gradle = gradle.replace(/android\s*\{/, (match) => match + signingBlock);
if (!/buildTypes\s*\{\s*release\s*\{/.test(gradle)) {
  throw new Error("Could not locate release build type.");
}
gradle = gradle.replace(
  /(buildTypes\s*\{\s*release\s*\{)/,
  "$1\n            signingConfig signingConfigs.linguaplayRelease"
);
fs.writeFileSync(gradleFile, gradle);
console.log("LinguaPlay release signing configured.");
